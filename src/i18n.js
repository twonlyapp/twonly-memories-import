// Every text the page shows, in English and German.
//
// The language defaults to English (also in tests and before the page sets
// one). The page picks the visitor's language at start; the conversion
// workers get it with every job, since they cannot read the page's choice.

export const LANGUAGES = ['en', 'de'];
const LOCALES = { en: 'en', de: 'de-DE' };

let current = 'en';

export function setLanguage(lang) {
  current = LANGUAGES.includes(lang) ? lang : 'en';
}

export function language() {
  return current;
}

export function locale() {
  return LOCALES[current];
}

/** The preferred language from a list like `navigator.languages`. */
export function preferredLanguage(candidates = []) {
  for (const candidate of candidates) {
    const base = String(candidate || '').toLowerCase().split('-')[0];
    if (LANGUAGES.includes(base)) return base;
  }
  return 'en';
}

/** The text for `key`; function entries take the arguments. */
export function t(key, ...args) {
  const entry = MESSAGES[current][key] ?? MESSAGES.en[key];
  if (entry === undefined) throw new Error(`missing text ${key}`);
  return typeof entry === 'function' ? entry(...args) : entry;
}

